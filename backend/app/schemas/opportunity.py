from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field
from backend.app.schemas.spatial import CompetitionAnalysisResult
from backend.app.schemas.service_gap import ServiceGapResult


class FactorScore(BaseModel):
    name: str
    value: float
    weight: float
    description: str


class OpportunityRequest(BaseModel):
    city_id: str = Field(default="pune", description="Target city identifier")
    category_id: str = Field(default="healthcare", description="Category slug or business type (e.g. 'Cafe', 'Pharmacy', 'healthcare')")
    business_type: Optional[str] = Field(default=None, description="Explicit business type (e.g. 'Cafe')")
    latitude: float = Field(default=18.5074, description="Target location latitude")
    longitude: float = Field(default=73.8077, description="Target location longitude")
    radius_meters: float = Field(default=2000.0, ge=500.0, le=20000.0, description="Catchment buffer radius")
    population_proxy: Optional[int] = Field(default=None, description="Estimated catchment population proxy")
    accessibility_proxy: Optional[float] = Field(default=None, ge=0.0, le=100.0, description="Accessibility indicator (0-100)")
    competitors_count: Optional[int] = Field(default=None, description="Known competitor count")
    hospitals_count: Optional[int] = Field(default=None)
    schools_count: Optional[int] = Field(default=None)
    colleges_count: Optional[int] = Field(default=None)
    offices_count: Optional[int] = Field(default=None)
    transit_stops_count: Optional[int] = Field(default=None)


class OpportunityResponse(BaseModel):
    city_id: str
    category_id: str
    latitude: float
    longitude: float
    radius_meters: float
    opportunity_score: int = Field(..., ge=0, le=100, description="Generated multi-factor opportunity score")
    opportunity_level: str = Field(..., description="'High', 'Medium', or 'Low'")
    suitability_label: str = Field(default="Good", description="'Poor', 'Fair', 'Good', or 'Excellent'")
    confidence_level: str = Field(default="Medium", description="'High', 'Medium', or 'Low'")
    is_provisional: bool = Field(default=False)
    weighted_base_score: float = Field(default=0.0)
    fuzzy_suitability_score: float = Field(default=0.0)
    factors: List[FactorScore]
    reasons: List[str] = Field(..., description="Explainable justifications for why this area scored well")
    risks: List[str] = Field(..., description="Honest risks and data limitations to evaluate")
    positive_drivers: List[str] = Field(default_factory=list)
    negative_risks: List[str] = Field(default_factory=list)
    missing_data_warnings: List[str] = Field(default_factory=list)
    practical_recommendation: str = Field(default="")
    executive_summary: str = Field(default="")
    competition: CompetitionAnalysisResult
    service_gap: ServiceGapResult
    data_mode: str = "live"
    disclaimer: str = (
        "Location suitability score generated by deterministic multi-criteria decision analysis + Mamdani fuzzy inference. "
        "Not a commercial revenue guarantee."
    )
    formula_documentation: str = Field(
        default="final_score = round(0.70 * MCDA_weighted_factors + 0.30 * fuzzy_suitability_score)"
    )
